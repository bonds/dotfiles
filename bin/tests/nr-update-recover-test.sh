#!/usr/bin/env bash
# nr-update-recover tests — the files an --update owns, and what a re-run resets.
#
# The premise: versions of update-managed packages are never hand-edited, so a
# leftover copy of one is pipeline output and gets reset from main. A script
# (`nr-pins`) and anything outside .config/nix are not, and must survive.
#
# Same throwaway layout as bin/tests/nr-guard-test.sh:
#
#   <root>/.local/share/dotfiles/bare        bare git dir, work tree = <root>
#   <root>/<files>                           the apply checkout
#
#   bash ~/bin/tests/nr-update-recover-test.sh
set -uo pipefail

export GIT_AUTHOR_NAME=t GIT_AUTHOR_EMAIL=t@t GIT_COMMITTER_NAME=t GIT_COMMITTER_EMAIL=t@t

RECOVER=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/nr-update-recover
T=/tmp/nr-update-recover-tests
pass=0
fail=0

ok() { printf '  PASS  %s\n' "$1"; pass=$((pass + 1)); }
bad() { printf '  FAIL  %s\n' "$1"; fail=$((fail + 1)); }

setup() {
	rm -rf "$T"
	mkdir -p "$T/.local/share/dotfiles" \
		"$T/.config/nix/modules/overlays/x" \
		"$T/.config/nix/pkgs/swival"
	printf 'lock1\n' >"$T/.config/nix/flake.lock"
	printf 'pins1\n' >"$T/.config/nix/flake-pins.json"
	printf 'pin1\n' >"$T/.config/nix/modules/overlays/x/default.nix"
	printf 'wheels1\n' >"$T/.config/nix/pkgs/swival/sources.nix"
	# The updater is what marks sources.nix as update output — the derivation reads
	# the tree, so the fixture has to look like one.
	printf '#!/bin/sh\n# rewrites sources.nix\n' >"$T/.config/nix/pkgs/swival/update.sh"
	printf 'a1\n' >"$T/a.conf"
	git init -q --bare "$T/.local/share/dotfiles/bare"
	git --git-dir="$T/.local/share/dotfiles/bare" --work-tree="$T" config core.bare false
	git --git-dir="$T/.local/share/dotfiles/bare" --work-tree="$T" config user.name t
	git --git-dir="$T/.local/share/dotfiles/bare" --work-tree="$T" config user.email t@t
	g add .config/nix/flake.lock .config/nix/flake-pins.json \
		.config/nix/modules/overlays/x/default.nix \
		.config/nix/pkgs/swival/sources.nix .config/nix/pkgs/swival/update.sh a.conf
	g commit -q -m init
	git --git-dir="$T/.local/share/dotfiles/bare" branch -M main
}

g() { git -C "$T" --git-dir="$T/.local/share/dotfiles/bare" --work-tree="$T" "$@"; }

recover() {
	out=$(NR_RECOVER_ROOT=$T HOME=$T GIT_CONFIG_NOSYSTEM=1 bash "$RECOVER" "$@" 2>&1)
	status=$?
}

echo "nr-update-recover"

# 1. A clean tree is a first run: silent, exit 0.
setup
recover
[ "$status" -eq 0 ] && ok "clean tree exits 0" || bad "clean tree exited $status"
[ -z "$out" ] && ok "clean tree says nothing" || bad "clean tree spoke: $out"

# 2. Interrupted during `nix flake update`: flake.lock half-written.
setup
printf 'lock-halfwritten\n' >"$T/.config/nix/flake.lock"
recover
[ "$status" -eq 0 ] && ok "recovers a half-written flake.lock" || bad "exited $status: $out"
[ "$(cat "$T/.config/nix/flake.lock")" = lock1 ] && ok "restored the lock from main" \
	|| bad "kept the half-written lock: $(cat "$T/.config/nix/flake.lock")"
printf '%s' "$out" | grep -q 'recovering an interrupted update' && ok "says what it did" || bad "silent recovery"

# 3. Interrupted during the update scripts: the pin registry half-written.
setup
printf 'pins-halfwritten\n' >"$T/.config/nix/flake-pins.json"
recover
[ "$(cat "$T/.config/nix/flake-pins.json")" = pins1 ] && ok "restored the registry from main" \
	|| bad "kept $(cat "$T/.config/nix/flake-pins.json")"

# 4. An overlay bump half-applied — pipeline output like any other, and the one
#    that used to make the guard refuse to apply main. The overlay has an
#    update.sh beside it, which is how it is recognised.
setup
printf '#!/bin/sh\n# bumps default.nix\n' >"$T/.config/nix/modules/overlays/x/update.sh"
printf 'pin-halfbumped\n' >"$T/.config/nix/modules/overlays/x/default.nix"
recover
[ "$status" -eq 0 ] && ok "recovers an overlay bump" || bad "exited $status"
[ "$(cat "$T/.config/nix/modules/overlays/x/default.nix")" = pin1 ] \
	&& ok "restored the overlay pin from main" || bad "kept the half-bumped pin"

# 5. pkgs/swival/sources.nix: regenerated by update.sh, and the file that was
#    missing from nr's commit list, so every bump left $HOME dirty.
setup
printf 'wheels2\n' >"$T/.config/nix/pkgs/swival/sources.nix"
recover
[ "$(cat "$T/.config/nix/pkgs/swival/sources.nix")" = wheels1 ] \
	&& ok "restored swival's sources.nix from main" || bad "kept the half-written wheels"

# 6. `nr-pins` is a script people edit (5824dcd): never restored.
setup
printf 'nr-pins-v1\n' >"$T/.config/nix/nr-pins"
g add .config/nix/nr-pins
g commit -q -m "add nr-pins"
printf 'mid-edit\n' >"$T/.config/nix/nr-pins"
recover
[ "$(cat "$T/.config/nix/nr-pins")" = mid-edit ] && ok "left a mid-edit nr-pins alone" \
	|| bad "discarded nr-pins"

# 7. Nothing outside .config/nix is ever touched — an update never writes there.
setup
printf 'a2\n' >"$T/a.conf"
recover
[ "$status" -eq 0 ] && ok "ignores a file outside .config/nix" || bad "exited $status"
[ "$(cat "$T/a.conf")" = a2 ] && ok "left it alone" || bad "touched $T/a.conf"

# 8. --paths prints the same set, absolute and existing only, for `git add`.
setup
out=$(NR_RECOVER_ROOT=$T HOME=$T GIT_CONFIG_NOSYSTEM=1 bash "$RECOVER" --paths)
printf '%s
' "$out" | grep -qx "$T/.config/nix/pkgs/swival/sources.nix" \
	&& ok "--paths lists swival's sources.nix" || bad "--paths omitted sources.nix"
nonabs=$(printf '%s\n' "$out" | grep -v '^/' || true)
[ -z "$nonabs" ] && ok "--paths is absolute" || bad "--paths has relative entries: $nonabs"
printf '%s\n' "$out" | grep -qv "^$T/" && bad "--paths escaped the fixture" \
	|| ok "--paths is rooted in the apply tree"
rm -f "$T/.config/nix/flake-pins.json"
out=$(NR_RECOVER_ROOT=$T HOME=$T GIT_CONFIG_NOSYSTEM=1 bash "$RECOVER" --paths)
printf '%s\n' "$out" | grep -q 'flake-pins.json' && bad "--paths lists a missing file" \
	|| ok "--paths skips files that do not exist"
printf '%s\n' "$out" | grep -q 'a\.conf' && bad "--paths escaped .config/nix" \
	|| ok "--paths stays inside .config/nix"

printf '\n== summarized: %d passed, %d failed ==\n' "$pass" "$fail"
[ "$fail" -eq 0 ]
